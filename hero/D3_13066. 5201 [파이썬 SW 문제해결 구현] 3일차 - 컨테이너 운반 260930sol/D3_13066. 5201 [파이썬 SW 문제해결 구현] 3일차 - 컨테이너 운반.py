import sys
sys.stdin = open("D3_13066. 5201 [파이썬 SW 문제해결 구현] 3일차 - 컨테이너 운반/input.txt", "r")

# 테스트케이스가 몇 개인지 입력받음
T = int(input())

# 테스트케이스마다 아래 과정을 반복할거임 ㅇㅇ
for tc in range(1, T + 1):
    N, M = map(int, input().split())  # N: 컨테이너 수, M: 트럭 수
    list_wi = list(map(int, input().split()))  # N개의 컨테이너 각각의 무게
    list_ti = list(map(int, input().split()))  # M대 트럭의 적재용량

    # 우선 문제풀이 원리에 대해서 생각해봄
    # 제일 무거운 컨테이너를 적재용량이 제일 큰 트럭이 맡는게 맞는거같음 ㅇㅇ
    # 문제에서 구하라고 한 것은, 옮겨진 화물 전체의 무게이므로
    # list_wi와 list_ti 내부의 순서는 상관없다고 생각함 ㅇㅇ
    # 따라서 내림차순으로 정렬을 하고
    # 적재용량이 큰 트럭부터 시작하여 순서대로 컨테이너를 하나씩 맡는 방향으로 가보고자 함 ㅇㅇ
    # 그러다가 컨테이너 무게가 무거워서 옮길 수 없다면
    # 그 다음 컨테이너로 넘어가서 판단하는 로직도 필요하다고 생각함 ㅇㅇ
    # 내가 볼 때 엣지케이스로 생각해야하는 것은
    # 1. M > N이라서 N개를 배정하고도 남는 경우가 생기는 것
    # 2. 트럭의 적재용량이 다들 작아서 1개의 컨테이너 조차 옮기지 못하는 것

    # -> 그리디 써볼거임 ㅇㅇ

    # 무거운 컨테이너부터 확인하려고 내림차순 정렬함
    # 이제 list_wi[0]이 남아있는 컨테이너 중 제일 무거운거임 ㅇㅇ
    list_wi.sort(reverse=True)

    # 적재용량이 큰 트럭부터 컨테이너를 맡기려고 내림차순 정렬함
    list_ti.sort(reverse=True)

    # print(N, M)
    # print(list_wi)
    # print(list_ti)

    # 옮긴 컨테이너의 무게를 여기에 계속 더할거임
    # 아무것도 못 옮기면 그대로 0을 출력하라고 했기 때문에
    # 초기값을 0으로 두고 컨테이너를 옮길 수 없는 경우에는 변화가 없어서 0으로 출력됨 ㅇㅇ
    total_weight = 0

    # 트럭을 하나씩 확인함
    # i는 현재 확인하고 있는 트럭의 인덱스임
    for i in range(len(list_ti)):
        # 컨테이너가 남아있고, 제일 무거운 컨테이너를 현재 트럭이 못 싣는 동안 반복함
        # list_wi부터 확인하니까 리스트가 비었으면 list_wi[0]은 확인하지 않음
        # 그래서 빈 리스트의 0번 인덱스를 꺼내려다가 에러나는 걸 막을 수 있음 ㅇㅇ
        while list_wi and list_ti[i] < list_wi[0]:
            # 현재 트럭도 못 싣는 무게면, 뒤에 있는 더 작은 트럭들도 못 싣는거임
            # 따라서 이 컨테이너는 제외하고 다음 컨테이너를 확인하면 됨
            # pop(0)을 하면 맨 앞의 값이 빠지고, 그 다음 값이 0번 자리에 오게 됨 ㅇㅇ
            list_wi.pop(0)

        # 컨테이너가 다 없어졌다면 더 확인할 필요가 없음
        # 트럭이 남아있어도 실을 컨테이너가 없으니까 여기서 끝내면 됨 ㅇㅇ
        if not list_wi:
            # 트럭을 순회하는 for문을 종료함
            break

        # 여기까지 왔으면 list_wi[0]은 현재 트럭에 실을 수 있는 가장 무거운 컨테이너임
        # pop(0)으로 그 무게를 꺼내서 합계에 더함
        # 동시에 리스트에서 제거되니까 다음 트럭이 같은 컨테이너를 또 싣지 않게 됨 ㅇㅇ
        total_weight += list_wi.pop(0)

    # 모든 트럭의 배정이 끝났거나 컨테이너가 다 없어졌으면, 옮긴 무게의 합을 출력함
    print(f'#{tc} {total_weight}')