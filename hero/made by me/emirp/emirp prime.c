#include <stdio.h>


// 문제에서 주어질 수 있는 가장 큰 수
#define MAX_N 1000000


// ============================================================
// 숫자의 자릿수를 거꾸로 뒤집는 함수
// ============================================================

int reverseNumber(int n) {

    int reversed = 0;

    // n의 각 자릿수를 뒤에서부터 하나씩 가져온다.
    //
    // 예) n = 123
    //
    // 1번째 반복
    // 123 % 10 = 3
    // reversed = 3
    //
    // 2번째 반복
    // 12 % 10 = 2
    // reversed = 3 * 10 + 2 = 32
    //
    // 3번째 반복
    // 1 % 10 = 1
    // reversed = 32 * 10 + 1 = 321
    //
    // 따라서 123 -> 321이 된다.
    while (n > 0) {

        // n의 마지막 자릿수를 가져온다.
        int digit = n % 10;

        // 기존 숫자를 한 자리 왼쪽으로 밀고
        // 마지막 자릿수를 추가한다.
        reversed = reversed * 10 + digit;

        // 사용한 마지막 자릿수를 제거한다.
        n = n / 10;
    }

    return reversed;
}


int main() {

    // ============================================================
    // 1. 에라토스테네스의 체로 1 ~ 1,000,000의 소수를 미리 구하기
    // ============================================================

    // isPrime[i]가
    // 1이면 i는 소수
    // 0이면 i는 소수가 아님
    //
    // C에서는 bool 대신 int 배열을 사용해서
    // 1과 0으로 소수 여부를 표현한다.
    static int isPrime[MAX_N + 1];


    // 처음에는 모든 숫자가 소수라고 가정하고
    // 2부터 1,000,000까지 1로 만들어준다.
    for (int i = 2; i <= MAX_N; i++) {
        isPrime[i] = 1;
    }

    // static 배열은 처음에 자동으로 0으로 초기화되므로
    // isPrime[0], isPrime[1]은 이미 0이다.
    //
    // 즉 0과 1은 소수가 아닌 상태로 시작한다.


    // 2부터 √1,000,000까지만 확인하면
    // 1,000,000 이하의 합성수를 전부 지울 수 있다.
    //
    // i * i <= MAX_N으로 작성하면
    // sqrt()를 따로 사용하지 않아도 된다.
    for (int i = 2; i * i <= MAX_N; i++) {

        // i가 아직 소수라면
        if (isPrime[i]) {

            // i의 배수들은 소수가 아니므로 0으로 바꾼다.
            //
            // i * 2부터 시작하지 않고 i * i부터 시작하는 이유:
            // i * i보다 작은 i의 배수들은
            // 앞에서 더 작은 수를 검사할 때 이미 지워졌기 때문이다.
            //
            // 예) i = 5라면
            // 10은 2의 배수를 지울 때,
            // 15는 3의 배수를 지울 때,
            // 20은 2의 배수를 지울 때 이미 지워졌다.
            // 따라서 25부터 확인하면 된다.
            for (int j = i * i; j <= MAX_N; j += i) {
                isPrime[j] = 0;
            }
        }
    }


    // ============================================================
    // 2. 어떤 숫자가 emirp인지 미리 확인하기
    // ============================================================

    // emirp[p]가
    // 1이면 p는 emirp
    // 0이면 p는 emirp가 아님
    //
    // static 배열이므로 처음에는 전부 0으로 초기화된다.
    static int emirp[MAX_N + 1];


    // 문제의 최소 범위가 10이므로 10부터 확인한다.
    for (int p = 10; p <= MAX_N; p++) {

        // emirp가 되려면 우선 p 자체가 소수여야 한다.
        if (isPrime[p]) {

            // p의 자릿수를 거꾸로 뒤집는다.
            //
            // 예)
            // p = 13
            // reverseNumber(13) = 31
            //
            // 따라서 q = 31이 된다.
            int q = reverseNumber(p);


            // emirp가 되기 위한 조건
            //
            // 조건 1. 뒤집은 수 q도 소수여야 한다.
            // 조건 2. p와 q가 서로 다른 수여야 한다.
            //
            // 예)
            // 13 -> 31
            // 13도 소수이고 31도 소수이며 서로 다르다.
            // 따라서 13은 emirp이다.
            //
            // 반면
            // 131 -> 131
            // 둘 다 소수이지만 자기 자신과 같기 때문에
            // 회문 소수이고 emirp는 아니다.
            if (isPrime[q] && p != q) {
                emirp[p] = 1;
            }
        }
    }


    // ============================================================
    // 3. emirp의 누적합 만들기
    // ============================================================

    // 테스트 케이스마다 L부터 R까지 전부 반복하면서
    // emirp인지 확인하면 같은 숫자를 계속 확인하게 된다.
    //
    // 따라서 emirp의 개수를 미리 누적해서 저장한다.
    //
    // prefix[i]
    // = 1부터 i까지 존재하는 emirp의 총 개수
    static int prefix[MAX_N + 1];


    for (int i = 1; i <= MAX_N; i++) {

        // 지금까지 발견한 emirp의 개수
        // +
        // 현재 숫자 i가 emirp인지 여부(0 또는 1)
        prefix[i] = prefix[i - 1] + emirp[i];
    }


    // 예를 들어 emirp가 아래처럼 있다고 생각하면
    //
    // 숫자      10 11 12 13 14 15 16 17 ...
    // emirp      0  0  0  1  0  0  0  1 ...
    //
    // prefix는
    //
    // 숫자      10 11 12 13 14 15 16 17 ...
    // prefix     0  0  0  1  1  1  1  2 ...
    //
    // 이런 식으로 지금까지 나온 emirp의 개수가 저장된다.


    // ============================================================
    // 4. 테스트 케이스 입력받기
    // ============================================================

    int T;
    scanf("%d", &T);


    for (int testCase = 1; testCase <= T; testCase++) {

        // emirp의 개수를 구할 구간
        int L, R;
        scanf("%d %d", &L, &R);


        // prefix[R]
        // = 1 ~ R까지의 emirp 개수
        //
        // prefix[L - 1]
        // = 1 ~ L-1까지의 emirp 개수
        //
        // 따라서 둘을 빼면
        // L ~ R 사이의 emirp만 남는다.
        //
        // 예)
        // 1 ~ 100까지 emirp가 8개이고
        // 1 ~ 9까지 emirp가 0개라면
        //
        // 10 ~ 100의 emirp 개수
        // = 8 - 0
        // = 8
        int answer = prefix[R] - prefix[L - 1];


        // SWEA 출력 형식
        printf("#%d %d\n", testCase, answer);
    }


    return 0;
}
