#include <iostream>
#include <vector>
#include <string>
#include <algorithm>

using namespace std;


// 문제에서 주어질 수 있는 가장 큰 수
const int MAX_N = 1000000;


int main() {

    // ============================================================
    // 1. 에라토스테네스의 체로 1 ~ 1,000,000의 소수를 미리 구하기
    // ============================================================

    // isPrime[i]가
    // true이면 i는 소수
    // false이면 i는 소수가 아님
    //
    // 처음에는 모든 숫자가 소수라고 가정하고 true로 채운다.
    vector<bool> isPrime(MAX_N + 1, true);

    // 0과 1은 소수가 아니므로 false로 바꿔준다.
    isPrime[0] = false;
    isPrime[1] = false;


    // 2부터 √1,000,000까지만 확인하면
    // 1,000,000 이하의 합성수를 전부 지울 수 있다.
    //
    // i * i <= MAX_N으로 작성하면
    // sqrt()를 따로 사용하지 않아도 된다.
    for (int i = 2; i * i <= MAX_N; i++) {

        // i가 아직 소수라면
        if (isPrime[i]) {

            // i의 배수들은 소수가 아니므로 false로 바꾼다.
            //
            // i * 2부터 시작하지 않고 i * i부터 시작하는 이유:
            // i * i보다 작은 i의 배수들은
            // 앞에서 더 작은 수를 검사할 때 이미 지워졌기 때문이다.
            //
            // 예) i = 5라면
            // 10은 2의 배수를 지울 때,
            // 15는 3의 배수를 지울 때,
            // 20은 2의 배수를 지울 때 이미 지워졌다.
            // 따라서 25부터 확인하면 된다.
            for (int j = i * i; j <= MAX_N; j += i) {
                isPrime[j] = false;
            }
        }
    }


    // ============================================================
    // 2. 어떤 숫자가 emirp인지 미리 확인하기
    // ============================================================

    // emirp[p]가
    // 1이면 p는 emirp
    // 0이면 p는 emirp가 아님
    vector<int> emirp(MAX_N + 1, 0);


    // 문제의 최소 범위가 10이므로 10부터 확인한다.
    for (int p = 10; p <= MAX_N; p++) {

        // emirp가 되려면 우선 p 자체가 소수여야 한다.
        if (isPrime[p]) {

            // p의 자릿수를 거꾸로 뒤집는다.
            //
            // 예)
            // p = 13
            //
            // to_string(p)  -> "13"
            // reverse()     -> "31"
            // stoi("31")    -> 31
            //
            // 따라서 q = 31이 된다.
            string reversed = to_string(p);

            reverse(reversed.begin(), reversed.end());

            int q = stoi(reversed);


            // emirp가 되기 위한 조건
            //
            // 조건 1. 뒤집은 수 q도 소수여야 한다.
            // 조건 2. p와 q가 서로 다른 수여야 한다.
            //
            // 예)
            // 13 -> 31
            // 13도 소수이고 31도 소수이며 서로 다르다.
            // 따라서 13은 emirp이다.
            //
            // 반면
            // 131 -> 131
            // 둘 다 소수이지만 자기 자신과 같기 때문에
            // 회문 소수이고 emirp는 아니다.
            if (isPrime[q] && p != q) {
                emirp[p] = 1;
            }
        }
    }


    // ============================================================
    // 3. emirp의 누적합 만들기
    // ============================================================

    // 테스트 케이스마다 L부터 R까지 전부 반복하면서
    // emirp인지 확인하면 같은 숫자를 계속 확인하게 된다.
    //
    // 따라서 emirp의 개수를 미리 누적해서 저장한다.
    //
    // prefix[i]
    // = 1부터 i까지 존재하는 emirp의 총 개수
    vector<int> prefix(MAX_N + 1, 0);


    for (int i = 1; i <= MAX_N; i++) {

        // 지금까지 발견한 emirp의 개수
        // +
        // 현재 숫자 i가 emirp인지 여부(0 또는 1)
        prefix[i] = prefix[i - 1] + emirp[i];
    }


    // 예를 들어 emirp가 아래처럼 있다고 생각하면
    //
    // 숫자      10 11 12 13 14 15 16 17 ...
    // emirp      0  0  0  1  0  0  0  1 ...
    //
    // prefix는
    //
    // 숫자      10 11 12 13 14 15 16 17 ...
    // prefix     0  0  0  1  1  1  1  2 ...
    //
    // 이런 식으로 지금까지 나온 emirp의 개수가 저장된다.


    // ============================================================
    // 4. 테스트 케이스 입력받기
    // ============================================================

    int T;
    cin >> T;


    for (int testCase = 1; testCase <= T; testCase++) {

        // emirp의 개수를 구할 구간
        int L, R;
        cin >> L >> R;


        // prefix[R]
        // = 1 ~ R까지의 emirp 개수
        //
        // prefix[L - 1]
        // = 1 ~ L-1까지의 emirp 개수
        //
        // 따라서 둘을 빼면
        // L ~ R 사이의 emirp만 남는다.
        //
        // 예)
        // 1 ~ 100까지 emirp가 8개이고
        // 1 ~ 9까지 emirp가 0개라면
        //
        // 10 ~ 100의 emirp 개수
        // = 8 - 0
        // = 8
        int answer = prefix[R] - prefix[L - 1];


        // SWEA 출력 형식
        cout << "#" << testCase << " " << answer << '\n';
    }


    return 0;
}
