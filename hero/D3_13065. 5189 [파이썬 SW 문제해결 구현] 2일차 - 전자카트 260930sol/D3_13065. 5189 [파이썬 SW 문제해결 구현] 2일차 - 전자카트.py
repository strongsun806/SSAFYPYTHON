import sys
sys.stdin = open("D3_13065. 5189 [파이썬 SW 문제해결 구현] 2일차 - 전자카트/input.txt", "r")

# 테스트케이스 개수를 입력받음
T = int(input())

# 테스트케이스 번호를 1부터 T까지 쓰려고 T + 1로 설정함
# range는 끝값을 포함하지 않으므로, T까지 나오려면 끝값을 T + 1로 써야함 ㅇㅇ
for tc in range(1, T + 1):
    # 구역의 개수를 입력받음
    # 구역 번호는 1부터 N까지 있는거임
    N = int(input())

    # 각 구역 사이의 배터리 소모량을 저장할 2차원 리스트임
    matrix_NxN = []

    # 구역이 N개라서 출발 구역에 해당하는 행도 N개를 입력받아야함
    # range(N)은 0부터 N-1까지이므로 총 N번 반복하는거임 ㅇㅇ
    for i in range(N):
        # 이번에 입력받을 한 행을 담을 빈 리스트임
        row = []

        # 한 줄에 있는 숫자들을 정수로 바꾸고 row에 하나씩 넣음
        row.extend(map(int, input().split()))

        # 완성된 한 행을 matrix에 추가함
        matrix_NxN.append(row)

    # 1번은 표현되는 경로에서 항상 처음과 끝에 위치하며
    # 나머지 2부터 N까지 N-1개의 번호들이 순서만 바꾸어 나열되는 순열 중에서
    # 배터리 소모량이 가장 작은 값을 찾아내야한다.
    # (순열: 서로 다른 N개에서 R개를 중복없이 순서를 고려하여 나열하는 것)
    # 1을 제외하고 나머지 N-1개의 숫자들의 순열을 구한 뒤에
    # 앞뒤에 1을 붙인 것에 대해서 배터리 소모량을 계산하여 최솟값을 구해보려함 ㅇㅇ

    # matrix의 행 번호가 출발, 열 번호가 도착임 ㅇㅇ

    # 2부터 N까지의 번호를 현재 선택한 순서대로 담을거임
    # 여기는 시작점과 도착점인 1을 제외한 중간 경로만 들어감 ㅇㅇ
    path_electronic_cart = []

    # 각 구역 번호를 이미 골랐는지 표시할 리스트임
    # 0은 아직 안 골랐다는 뜻이고, 1은 이미 골랐다는 뜻임
    # 구역 번호를 그대로 인덱스로 쓰려고 N + 1칸을 만드는거임
    # 예를 들어 N이 4면 인덱스 4까지 필요하니까 [0, 0, 0, 0, 0]으로 5칸이 필요함
    # 0번 칸은 사용하지 않고, 구역 번호 2는 인덱스 2에서 확인하는 식임 ㅇㅇ
    is_already_used = [0] * (N + 1)

    # 앞뒤에 1까지 붙인 완성된 경로들을 모두 저장할거임
    all_path = []

    # a는 지금까지 중간 경로에 고른 번호의 개수임
    # 구역 번호나 리스트 인덱스가 아니라, 몇 개 골랐는지를 세는 값임 ㅇㅇ
    def permutation(a):
        # 기저 조건
        # 전체 N개 구역 중에서 1번은 앞뒤에 따로 붙일거니까
        # 여기서는 2부터 N까지 총 N-1개의 번호만 고르면 됨
        # 예를 들어 N이 4면 2, 3, 4의 순서를 정해야 하니까 3개 고르면 완성임 ㅇㅇ
        if a == N - 1:
            # 완성된 경로의 시작점은 항상 1번이므로 먼저 1을 넣음
            # 매번 새 리스트를 만들어서 각각의 경로를 따로 저장하는거임
            path = [1]

            # 지금까지 고른 중간 구역들을 선택한 순서대로 꺼냄
            for i in path_electronic_cart:
                # 시작점 1 뒤에 중간 구역 번호들을 붙임
                path.append(i)

            # 마지막에는 다시 1번으로 돌아가야 하니까 1을 붙임
            # N이 4이고 중간 경로가 [2, 3, 4]라면 [1, 2, 3, 4, 1]이 됨
            # 중간 번호 N-1개에 앞뒤의 1 두 개를 붙였으므로 경로 길이는 N+1임 ㅇㅇ
            path.append(1)
            # print(path)

            # 완성된 경로 하나를 전체 경로 목록에 저장함
            all_path.append(path)

            # 경로가 완성됐으므로 번호를 더 고르지 않고 호출한 곳으로 돌아감
            return

    
        # 1번은 따로 붙일거니까 2번부터 N번까지만 선택 후보로 확인함
        # range는 끝값을 포함하지 않아서 N번까지 확인하려면 N + 1을 써야함
        # 예를 들어 N이 4면 range(2, 5)가 되어 2, 3, 4를 확인함 ㅇㅇ
        for i in range(2, N + 1):  # 2부터 N까지이므로
            # 현재 만들고 있는 경로에서 이미 고른 번호인지 확인함
            if is_already_used[i] == 1:
                # 이미 골랐다면 중복해서 넣으면 안 되니까 다음 후보로 넘어감
                continue

            # 이번에 i번 구역을 고를거니까 사용했다고 표시함
            is_already_used[i] = 1

            # 현재 경로의 맨 뒤에 i번 구역을 추가함
            path_electronic_cart.append(i)

            # 번호 하나를 더 골랐으니까 고른 개수 a를 1 늘려서 다음 선택을 진행함
            # 예를 들어 a가 0이었다면 이제 1개를 골랐으므로 permutation(1)을 호출함
            permutation(a + 1)

            # i를 고른 상태에서 만들 수 있는 경로들을 다 확인하고 돌아온거임
            # 이제 다른 후보를 골라봐야 하니까 방금 넣은 마지막 번호 i를 뺌
            path_electronic_cart.pop()

            # 경로에서 i를 뺐으니까 사용 표시도 다시 0으로 돌려놓음
            # 그래야 다른 순서의 경로를 만들 때 i를 다시 고를 수 있음 ㅇㅇ
            is_already_used[i] = 0
            
    # 처음에는 중간 구역을 하나도 고르지 않았으니까 a를 0으로 시작함
    permutation(0)
    # print(all_path)

    # 아직 경로의 소모량을 계산하지 않았으니까 최솟값을 무한대로 시작함
    # 그러면 처음 계산한 소모량이 이것보다 작아서 첫 최솟값으로 저장됨 ㅇㅇ
    min_sum_of_path = float('inf')


    # 저장된 모든 경로를 하나씩 확인함
    # 여기서 a는 경로 목록의 인덱스임
    # 함수 안의 a는 고른 개수였지만, 여기서는 별도로 쓰는 반복문 변수임 ㅇㅇ
    for a in range(len(all_path)):
        # 이번 경로의 배터리 소모량을 0부터 더할거임
        # 경로가 바뀔 때마다 새로 계산해야 하니까 반복문 안에서 0으로 설정함
        tmp = 0

        # 경로에 적힌 번호는 N+1개지만, 번호 사이를 이동하는 횟수는 N번임
        # 예를 들어 N이 4면 [1, 2, 3, 4, 1]에서
        # 1->2, 2->3, 3->4, 4->1로 총 4번 이동하는거임 ㅇㅇ
        # 따라서 range(N)으로 b를 0부터 N-1까지 사용함
        # 마지막에는 b가 N-1이고 b+1이 N이 되어, 마지막 두 번호 사이를 계산함
        for b in range(N):
            # all_path[a][b]는 현재 출발 구역이고, all_path[a][b+1]은 다음 도착 구역임
            # 구역 번호는 1부터 시작하지만 matrix 인덱스는 0부터 시작하니까 각각 1을 뺌
            # 예를 들어 2번->4번 소모량은 matrix_NxN[1][3]에서 가져오는거임
            # 이렇게 가져온 한 번의 이동 소모량을 이번 경로의 합계에 더함 ㅇㅇ
            tmp += matrix_NxN[(all_path[a][b]-1)][(all_path[a][b+1]-1)]

        # 이번 경로의 총 소모량이 지금까지의 최솟값보다 작은지 확인함
        if tmp < min_sum_of_path:
            # 더 작은 소모량을 찾았으므로 최솟값을 바꿔줌
            min_sum_of_path = tmp

    # 모든 경로를 비교해서 구한 최소 소모량을 정답으로 저장함
    answer = min_sum_of_path

    # 테스트케이스 번호와 정답을 출력함
    print(f'#{tc} {answer}')



